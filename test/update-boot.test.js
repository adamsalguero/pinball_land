test("update now is a scheduled task and an up-to-date nightly does not stop the wall", () => {
  const script = read("scripts/invoke-update.ps1");
  const updater = read("src/self-update.js");
  const control = read("public/control.js");
  const html = read("public/control.html");
  const register = read("scripts/register-update-tasks.ps1");
  const app = read("src/app.js");
  assert.match(script, /PinballLandUpdateNow/);
  assert.match(script, /Write-UpdateTrace "start"/);
  assert.match(script, /up-to-date; leaving the wall running/);
  assert.match(script, /nightly left the wall running/);
  const upToDate = script.indexOf("up-to-date; leaving the wall running");
  const stopCall = script.indexOf("  Stop-PinballTasks\n");
  assert.ok(upToDate > 0 && stopCall > upToDate, "the up-to-date check happens before the wall is stopped");
  assert.match(script, /if \(\(\$Mode -eq "nightly" -or \$Mode -eq "now"\) -and -not \$skipRestart\)/);
  assert.match(updater, /schtasks\.exe/);
  assert.match(updater, /\/TN", "PinballLandUpdateNow"/);
  assert.match(updater, /invoke \$\{mode\} requested/);
  assert.doesNotMatch(updater, /function launchDetachedUpdate/);
  assert.match(app, /launchScheduledUpdate\(\{ dataDir: updateDataDir, mode: "now" \}\)/);
  assert.match(app, /photo processor unavailable/);
  assert.match(control, /not started/);
  assert.match(control, /20000/);
  assert.match(html, /id="photo-processor"/);
  assert.match(register, /\$nowTask = "PinballLandUpdateNow"/);
  assert.match(read(".github/workflows/ci.yml"), /node scripts\/update-now-windows\.js/);
  assert.match(read(".github/workflows/ci.yml"), /node scripts\/boot-order-windows\.js/);
  const boot = script.slice(script.indexOf("function Invoke-BootSequence"), script.indexOf("function Test-GithubDns"));
  const quick = boot.indexOf("phase quick-check");
  const wall = boot.indexOf("Start-Wall");
  const zero = boot.indexOf("phase zero-scan");
  const upload = boot.indexOf("phase upload-check");
  const dns = boot.indexOf("phase dns-wait");
  const skip = boot.indexOf("phase update-skip");
  const plan = boot.indexOf("phase update-plan");
  const stage = boot.indexOf("phase update-stage");
  const swap = boot.indexOf("phase update-swap");
  assert.ok(quick > 0 && quick < wall && wall < zero && zero < upload && upload < dns, "boot opens the wall before it waits for DNS");
  assert.ok(dns < skip && skip < plan && plan < stage && stage < swap, "a missed network skips the update; a staged update swaps after the wall is up");
  assert.doesNotMatch(boot, /Stop-PinballTasks/);
  assert.match(boot.slice(swap), /Stop-PinballServer/);
  assert.match(boot.slice(swap), /Start-ServerOnly/);
  assert.doesNotMatch(boot.slice(swap), /Start-Wall/);
  const serverOnly = script.slice(script.indexOf("function Start-ServerOnly"), script.indexOf("function Invoke-BootSequence"));
  assert.match(serverOnly, /restarted the server only/);
  assert.match(serverOnly, /kiosk was dead; restarted windows/);
  assert.match(serverOnly, /phase wall-kiosk/);
  const bootCall = script.indexOf("Invoke-BootSequence", script.indexOf("function Invoke-BootSequence") + 10);
  const nightly = script.slice(bootCall, script.indexOf("Remove-TemporaryWallTask", bootCall));
  assert.ok(nightly.indexOf("phase update-plan") < nightly.indexOf("phase update-apply"));
  assert.ok(nightly.indexOf("phase update-apply") < nightly.indexOf("phase integrity"));
  assert.match(read("src/app.js"), /build: commitCache/);
  assert.match(read("public/display.js"), /PinballBuild\?\.watchBuild/);
  assert.match(read("public/present.js"), /PinballBuild\?\.watchBuild/);
  assert.match(read("public/control.js"), /PinballBuild\?\.watchBuild/);
  assert.match(read("public/build-watch.js"), /location\.reload\(\)/);
  assert.match(read("public/display.html"), /build-watch\.js/);
  assert.match(read("public/present.html"), /build-watch\.js/);
  assert.match(read("public/control.html"), /build-watch\.js/);
  assert.match(read("src/upload-check.js"), /function repairUploadPath/);
  assert.match(read("scripts/check-upload.js"), /--repair/);
  assert.doesNotMatch(read("src/upload-check.js"), /setInterval/);
  assert.match(read("public/guest.js"), /Can't reach Pinball Land right now/);
  assert.match(read("public/control.js"), /Can't reach Pinball Land right now/);
  assert.match(read("src/cloudflared.js"), /restart tunnel registration failed/);
  assert.match(read("src/cloudflared.js"), /tunnel not found\|register tunnel error/);
});

